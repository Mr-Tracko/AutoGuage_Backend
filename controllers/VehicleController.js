const Vehicle = require("../models/Vehicle");

const createVehicle = async (req, res) => {
    try {
        const vehicle = new Vehicle(req.body);
        await vehicle.save();
        res.status(201).json(vehicle);
    } catch (error) {
        res.status(400).json({
            error: error.message
        });
    }
};

const getAllVehicles = async (req, res) => {
    try {
        const vehicles = await Vehicle.find().populate("seller");
        res.json(vehicles);
    } catch (error) {
        res.status(500).json({
            error: error.message
        });
    }
};

const getVehiclesBySeller = async (req, res) => {
  try {
    const vehicles = await Vehicle.find({
      seller: req.params.sellerId
      //req.params is automatically generated by the express from the URL pattern you define in routes.
    }).populate("seller");

    res.json(vehicles);
  } catch (error) {
    res.status(500).json({
      error: error.message
    });
  }
};

const getVehicleById = async (req, res) => {
  try {
    const vehicle = await Vehicle.findById(req.params.id).populate("seller");

    if (!vehicle) {
      return res.status(404).json({ error: "Vehicle not found" });
    }

    res.json(vehicle);
  } catch (error) {
    res.status(500).json({
      error: error.message
    });
  }
};

module.exports = {
  createVehicle,
  getAllVehicles,
  getVehiclesBySeller,
  getVehicleById
};